# Латинская «i» внутри казахских слов вместо «і» («Кодекстiң») — частая подмена в текстах.
_LATIN_I_RE = re.compile(rf"(?<=[{UP}{LOW}])[iI]|[iI](?=[{LOW}])")


def fix_latin_i(text: str) -> str:
    return _LATIN_I_RE.sub(lambda m: "і" if m.group(0) == "i" else "І", text)


def is_kazakh(text: str) -> bool:
    """Решение на казахском: казахских букв много (в русском решении они только в названиях)."""
    sample = text[:20000]
    kz = sum(sample.count(ch) for ch in KZ_LETTERS)
    return kz > 200 and kz > len(sample) / 100


# --- заголовки блоков -> русские ключи ------------------------------------------------------------
def heading_key(key: str) -> str | None:
    """Казахский заголовок (без пробелов, заглавными) -> ключ, как у русского заголовка."""
    key = key.replace("I", "І")  # «Ш Е Ш І М Е Т Т I :» — латинская «I»
    if "ҮШІНШІ" in key:
        return "ТРЕТЬИЛИЦА"
    if key.startswith("ҚАРСЫТАЛАП"):
        return "ИСТЕЦПОВСТРЕЧНОМУИСКУ"
    for prefix in ("ТАЛАПҚОЮШЫ", "ТАЛАПКЕР"):
        if key.startswith(prefix):
            if re.search(r"ТАЛАБЫ|ТАЛАПТАРЫ|ТАЛАБЫН|ТАЛАПТАРЫН", key[len(prefix):]):
                return "ТРЕБОВАНИЯИСТЦА"
            return "ИСТЕЦ"
    simple = (
        ("ЖАУАПКЕР", "ОТВЕТЧИК"),
        ("ӨТІНІШБЕРУШІ", "ЗАЯВИТЕЛЬ"),
        ("АРЫЗБЕРУШІ", "ЗАЯВИТЕЛЬ"),
        ("СОТҚАҚАТЫСҚАН", "ВСУДЕУЧАСТВОВАЛИ"),
        ("СОТОТЫРЫСЫНАҚАТЫСҚАН", "ВСУДЕУЧАСТВОВАЛИ"),
        ("СИПАТТАУ", "ОПИСАТЕЛЬНАЯЧАСТЬ"),
        ("УӘЖДЕУ", "МОТИВИРОВОЧНАЯЧАСТЬ"),
        ("ҚАРАРБӨЛІГІ", "РЕЗОЛЮТИВНАЯЧАСТЬ"),
        ("СОТШЕШІМЕТТІ", "РЕШИЛ"),
        ("ШЕШІМЕТТІ", "РЕШИЛ"),
        ("ҰЙҒАРДЫ", "ОПРЕДЕЛИЛ"),
        ("ҚАУЛЫЕТТІ", "ПОСТАНОВИЛ"),
        ("ПРОКУРОР", "ПРОКУРОР"),
        ("МҮДДЕЛІ", "ЗАИНТЕРЕСОВАННЫЕЛИЦА"),
    )
    for prefix, ru in simple:
        if key.startswith(prefix):
            return ru
    return None


