def law_title(title_kz: str, kind: str | None = None) -> str:
    """«Тұрғын үй қатынастары туралы» -> «Закон «О жилищных отношениях»» (если перевод известен)."""
    t = re.sub(r"\s+", " ", title_kz).strip()
    t = re.sub(r"^Қазақстан\s+Республикасының\s+", "", t)
    word = "Кодекс" if kind and kind.lower().startswith("кодекс") else "Закон"
    ru = LAW_TITLES_KZ.get(t.lower())
    return f"{word} «{ru}»" if ru else f"{word} «{t[0].upper()}{t[1:]}»"


def _code_of(text: str) -> str | None:
    m = re.search(_TITLED, text)
    if m:
        return law_title(m.group(1), m.group(2))
    for ru, rx in _CODE_ANY:
        if rx.search(text):
            return ru
    return None


def _nearest_code_before(text: str, pos: int, reach: int = 1500) -> str | None:
    chunk = text[max(0, pos - reach):pos]
    best, best_at = None, -1
    for ru, rx in _CODE_ANY:
        for m in rx.finditer(chunk):
            if m.start() > best_at:
                best, best_at = ru, m.start()
    return best


def extract_citations_kz(text: str, expand) -> tuple[list[tuple[str, str]], list[str]]:
    """Статьи из казахского текста: [(закон, статья)] и фрагменты, где закон не определён.

    В казахском тексте закон стоит перед номером статьи: «Заңның 42-1-бабы», «АК-нің 350-бабы».
    """
    text = re.sub(r"\s+", " ", text)
    aliases: dict[str, str] = {}
    for m in _ALIAS_DEF_RE.finditer(text):
        source, alias = m.group(1), m.group(2).strip(" «»\"'")
        law = _code_of(source)
        if law and alias:
            aliases[alias] = law
    titles = {law_title(m.group(1)) for m in re.finditer(r"«([^«»]{3,200}?\s+туралы)»\s*(?:№\s*[\d\-]+\w*\s*)?Заң", text)}
    bare = aliases.get("Заң") or (next(iter(titles)) if len(titles) == 1 else None)

    found: list[tuple[str, str]] = []
    unresolved: list[str] = []
    prev_law, prev_end = None, -1
    for m in ARTICLE_KZ_RE.finditer(text):
        before = text[max(0, m.start() - 220):m.start()]
        law = None
        if prev_law and _CHAIN_GAP_RE.match(text[prev_end:m.start()]):
            law = prev_law
        if law is None:
            tm = _TITLE_BEFORE_RE.search(before)
            if tm:
                law = law_title(tm.group(1), tm.group(2))
        if law is None:
            for ru, rx in _CODE_BEFORE:
                if rx.search(before):
                    law = ru
                    break
        if law is None:
            for alias in sorted(aliases, key=len, reverse=True):
                if re.search(r"(?<![" + LOW + r"])" + re.escape(alias) + _GEN + _PAREN + _TAIL, before):
                    law = aliases[alias]
                    break
        if law is None and _THIS_CODE_RE.search(before):
            law = _nearest_code_before(text, m.start() - 20)
        if law is None and _LAW_WORD_RE.search(before):
            law = bare
        if law is None:
            unresolved.append(text[max(0, m.start() - 40): m.end() + 20].strip())
            prev_law = None
            continue
        prev_law, prev_end = law, m.end()
        for article in expand(re.sub(r"\s*және\s*", ", ", m.group(1))):
            found.append((law, article))
    return found, unresolved


