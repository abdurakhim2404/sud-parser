"""Правила для решений на казахском языке.

Казахские решения устроены так же, как русские, но другими словами:

    ҚАЗАҚСТАН РЕСПУБЛИКАСЫНЫҢ АТЫНАН / ШЕШІМ
    2025 жылғы 6 қараша   №4319-25-00-2/4637   Қызылорда қаласы
    Қызылорда қалалық сотының құрамында: …
    ТАЛАП ҚОЮШЫ: …   ЖАУАПКЕР: …   ТАЛАП ҚОЮШЫНЫҢ ТАЛАБЫ: …
    СИПАТТАУ БӨЛІГІ / УӘЖДЕУ БӨЛІГІ / ҚАРАР БӨЛІГІ
    ШЕШІМ ЕТТІ: Талап қоюы қанағаттандырылсын / ішінара қанағаттандырылсын /
                қанағаттандырудан бас тартылсын.
                Жауапкерден талап қоюшының пайдасына 333 333 теңге … өндірілсін.

Здесь — казахские слова и шаблоны. Основной разбор (extract.py) общий: казахские заголовки
переводятся в русские ключи, исходы — в русские формулировки, а статьи кодексов и законов
приводятся к тем же названиям, что и в русских решениях, чтобы статистика по обоим языкам
складывалась вместе.
"""
