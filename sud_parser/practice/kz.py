def split_payer_payee(clean: str) -> tuple[str, str] | None:
    """«Жауапкерден талап қоюшының пайдасына … өндірілсін» -> (плательщик, получатель).

    Плательщик стоит в исходном падеже (-дан/-ден/-тан/-тен/-нан/-нен), получатель — перед «пайдасына».
    """
    m = re.search(r"(?P<left>.*?)\bпайдасына\b", clean, re.I)
    if m:
        left = m.group("left")
    elif re.search(AWARD_KZ, clean, re.I):
        # «Жауапкерден … 181 000 теңге «Жаңақала» пәтер иелері кооперативіне өндірілсін» —
        # получатель в дательном падеже, без слова «пайдасына».
        left = re.split(AWARD_KZ, clean, maxsplit=1, flags=re.I)[0]
    else:
        return None
    abl = list(_ABLATIVE_RE.finditer(left))
    if not abl:
        return left, ""
    cut = abl[-1].end()
    return left[:cut], left[cut:]


